-- PayRelay schema v2: config-driven bank integrations.
--
-- Each bank speaks its own API dialect. Instead of one adapter class per bank, a bank's endpoint,
-- authentication, payload mapping and response interpretation live here as a versioned JSON spec.
-- Secrets are never stored: the spec names a secretRef, resolved from the environment at call time.

CREATE TABLE bank_configs (
    bank_code       VARCHAR(20)  PRIMARY KEY,
    display_name    VARCHAR(100) NOT NULL,
    enabled         BOOLEAN      NOT NULL,
    spec            TEXT         NOT NULL,
    version         BIGINT       NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Every saved version is kept, so any past request can be explained and any config restored.
CREATE TABLE bank_config_history (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_code       VARCHAR(20)  NOT NULL REFERENCES bank_configs (bank_code),
    version         BIGINT       NOT NULL,
    display_name    VARCHAR(100) NOT NULL,
    enabled         BOOLEAN      NOT NULL,
    spec            TEXT         NOT NULL,
    changed_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_bank_config_history UNIQUE (bank_code, version)
);

-- Which config version produced each bank call, plus a short note (e.g. "token refreshed").
ALTER TABLE step_attempts ADD COLUMN config_version BIGINT;
ALTER TABLE step_attempts ADD COLUMN note VARCHAR(300);

